import QRCode from "qrcode";
import { Lock } from "lucide-react";

type MembershipCardProps = {
  name: string | null | undefined;
  membershipNumber: string | null;
  status: string | undefined;
  memberSince: Date | null;
};

export async function MembershipCard({
  name,
  membershipNumber,
  status,
  memberSince,
}: MembershipCardProps) {
  const isPending = status === "PENDING";
  const isLapsed = status === "LAPSED";
  const unlocked = !isPending && !!membershipNumber;

  // The real number and QR are only generated once the account is activated,
  // so they never reach the browser for a pending member.
  const qrSvg = unlocked
    ? await QRCode.toString(membershipNumber, {
        type: "svg",
        margin: 1,
        width: 144,
        color: { dark: "#0B2E1B", light: "#FFFFFF" },
      })
    : null;

  return (
    <div className="overflow-hidden rounded-2xl bg-brand-forest p-5 text-white shadow-sm">
      <div className="flex items-start justify-between gap-4">
        <div className="min-w-0">
          <p className="text-xs uppercase tracking-widest text-white/60">
            Easy Run Klub
          </p>
          <p className="mt-1 truncate font-heading text-lg font-semibold">
            {name ?? "Member"}
          </p>

          <p className="mt-5 text-xs uppercase tracking-widest text-white/60">
            Membership ID
          </p>
          <p className="mt-1 text-2xl font-semibold tracking-wide">
            {unlocked ? membershipNumber : "ERK-••••••"}
          </p>

          {memberSince && unlocked && (
            <p className="mt-4 text-xs text-white/60">
              Member since{" "}
              {memberSince.toLocaleDateString("en-GB", {
                month: "long",
                year: "numeric",
              })}
            </p>
          )}
        </div>

        <div className="shrink-0">
          {qrSvg ? (
            <div
              className="overflow-hidden rounded-xl bg-white p-1.5"
              // Generated by us from the membership number; not user HTML.
              dangerouslySetInnerHTML={{ __html: qrSvg }}
            />
          ) : (
            <div className="flex h-[144px] w-[144px] flex-col items-center justify-center gap-2 rounded-xl border border-white/20 bg-white/10 text-center text-xs text-white/70">
              <Lock className="h-5 w-5" />
              Activate to unlock
            </div>
          )}
        </div>
      </div>

      {isLapsed && (
        <p className="mt-4 rounded-lg bg-orange-100 px-3 py-2 text-sm text-orange-900">
          Your monthly dues are overdue. Pay them to restore full access.
        </p>
      )}
    </div>
  );
}